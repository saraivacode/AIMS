#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AIMS Framework - Model Results Comparison Tool
==============================================

This module provides a command-line utility for loading, comparing, and visualizing
training results from multiple machine learning models within the AIMS (Adaptive and Intelligent
Management of Slicing) framework.

It consumes standardized JSON result files (generated by `ResultsManager`) and creates
tabular summaries and comparative plots.

Key Features:
    - Directory-wide automatic result discovery
    - Tabular metric comparison using pandas and tabulate
    - Multi-panel matplotlib and seaborn visualizations
    - Automatic identification of best-performing models by key metrics
    - Support for both directory-based scanning and explicit file listing
    - Optional CSV export and plot image saving for documentation purposes


Usage Examples:
```bash
    $ python compare_results.py --results-dir ./results
    $ python compare_results.py --files path/to/rf_results.json path/to/cb_results.json
```

Author: Tiago do Vale Saraiva
License: MIT
"""

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Optional

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from tabulate import tabulate

# -------------------------------------------------
# Global Defaults
# -------------------------------------------------
class GlobalDefaults:
    """Container for global default values."""

    # Impact classification
    IMPACT_CLASSES = ["Adequate", "Warning", "Severe", "Critical"]

def load_results(file_path: Path) -> Dict[str, Any]:
    """Load a single JSON result file."""
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def find_result_files(results_dir: Path) -> List[Path]:
    """Recursively find all AIMS JSON result files within a directory."""
    patterns = ["**/training_summary*.json", "**/training_results*.json"]
    files = {file for pattern in patterns for file in results_dir.glob(pattern)}
    return sorted(list(files))

def create_comparison_table(results_list: List[Dict[str, Any]]) -> pd.DataFrame:
    """Build a pandas DataFrame summarizing key metrics from multiple result files."""
    rows = []
    for result in results_list:
        model_info = result.get("model_info", {})
        data_info = result.get("data_info", {})
        split_info = data_info.get("split_info", {})
        metrics = result.get("metrics", {})
        cv_metrics = metrics.get("cross_validation", {})
        holdout_metrics = metrics.get("holdout", {})
        overall_holdout = holdout_metrics.get("overall", {})
        per_class_holdout = holdout_metrics.get("per_class", {})
        hpo_stats = result.get("performance", {}).get("hpo_stats", {})
        training_stats = result.get("performance", {}).get("training_stats", {})

        row = {
            "Model": model_info.get("model_name", "Unknown"),
            "Library": model_info.get("library", "N/A"),
            "Train Size": split_info.get("train_size"),
            "Test Size": split_info.get("holdout_size"),
            "Features": data_info.get("n_features"),
            "CV F1-Macro": f"{cv_metrics.get('mean_score', 0):.4f}",
            "CV Std": f"{cv_metrics.get('std_dev', 0):.4f}" if cv_metrics.get('std_dev') is not None else "N/A",
            "Test Accuracy": f"{overall_holdout.get('accuracy', 0):.4f}",
            "Test F1-Macro": f"{overall_holdout.get('macro_avg_f1', 0):.4f}",
            "F1 Adequate": f"{per_class_holdout.get('Adequate', {}).get('f1_score', 0):.3f}",
            "F1 Warning": f"{per_class_holdout.get('Warning', {}).get('f1_score', 0):.3f}",
            "F1 Severe": f"{per_class_holdout.get('Severe', {}).get('f1_score', 0):.3f}",
            "F1 Critical": f"{per_class_holdout.get('Critical', {}).get('f1_score', 0):.3f}",
            "Device": training_stats.get("inference_device", "N/A"),
            "HPO Trials": hpo_stats.get("n_trials"),
            "HPO Time (s)": f"{hpo_stats.get('optimization_time_seconds', 0):.1f}",
            "Fit Time (s)": f"{training_stats.get('fit_time_seconds', 0):.1f}",
            "Total Time (s)": f"{training_stats.get('total_run_time_seconds', 0):.1f}",
            "Parameters": training_stats.get("total_parameters"),
            "Best Epoch": training_stats.get("best_epoch"),
        }
        rows.append(row)

    return pd.DataFrame(rows)

def plot_metrics_comparison(df: pd.DataFrame, output_path: Optional[Path] = None):
    """Generate and optionally save a multi-panel comparison plot."""
    fig, axes = plt.subplots(2, 2, figsize=(14, 11))
    models = df['Model'].values

    # Accuracy Bar Chart
    ax = axes[0, 0]
    accuracies = pd.to_numeric(df['Test Accuracy'], errors='coerce').fillna(0).values
    bars = ax.bar(models, accuracies, color=sns.color_palette("viridis", len(models)))
    ax.set_ylabel('Accuracy')
    ax.set_title('Test Set Accuracy')
    ax.set_ylim(0, 1.05)
    for bar in bars:
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height(),
                f'{bar.get_height():.4f}', ha='center', va='bottom', fontsize=9)

    # CV vs Test F1-Macro
    ax = axes[0, 1]
    x = np.arange(len(models))
    width = 0.35
    cv_f1 = pd.to_numeric(df['CV F1-Macro'], errors='coerce').fillna(0).values
    test_f1 = pd.to_numeric(df['Test F1-Macro'], errors='coerce').fillna(0).values
    ax.bar(x - width / 2, cv_f1, width, label='CV F1-Macro', alpha=0.85)
    ax.bar(x + width / 2, test_f1, width, label='Test F1-Macro', alpha=0.85)
    ax.set_ylabel('F1-Macro')
    ax.set_title('F1-Macro: CV vs Test')
    ax.set_xticks(x)
    ax.set_xticklabels(models)
    ax.legend()

    # Per-Class F1 Heatmap
    ax = axes[1, 0]
    class_f1_cols = ['F1 Adequate', 'F1 Warning', 'F1 Severe', 'F1 Critical']
    class_f1_data = df[class_f1_cols].apply(pd.to_numeric, errors='coerce').fillna(0)
    sns.heatmap(class_f1_data.T, annot=True, fmt='.3f', cmap='YlGnBu',
                xticklabels=models, yticklabels=[c.replace('F1 ', '') for c in class_f1_cols],
                ax=ax, vmin=0.0, vmax=1.0, cbar_kws={'label': 'F1 Score'})
    ax.set_title('Per-Class F1 Scores (Test Set)')

    # Training Time Breakdown
    ax = axes[1, 1]
    hpo_times = pd.to_numeric(df['HPO Time (s)'], errors='coerce').fillna(0).values
    fit_times = pd.to_numeric(df['Fit Time (s)'], errors='coerce').fillna(0).values
    ax.bar(models, hpo_times, label='HPO Time', alpha=0.8)
    ax.bar(models, fit_times, bottom=hpo_times, label='Fit Time', alpha=0.8)
    ax.set_ylabel('Time (s)')
    ax.set_title('Training Time Breakdown')
    ax.legend()

    plt.tight_layout(pad=2.0)
    if output_path:
        plt.savefig(output_path, dpi=300, bbox_inches='tight')
        print(f"✓ Saved comparison plot to: {output_path}")
    plt.show()

def print_summary(df: pd.DataFrame):
    """Prints a console-friendly summary of the comparison DataFrame."""
    print("\n" + "=" * 80)
    print("MODEL COMPARISON SUMMARY")
    print("=" * 80)

    print("\n🏆 BEST PERFORMERS:")
    metrics_to_check = {
        "Test Accuracy": "highest",
        "Test F1-Macro": "highest",
        "F1 Critical": "highest",
        "Total Time (s)": "lowest",
    }
    for metric, direction in metrics_to_check.items():
        col_values = pd.to_numeric(df[metric], errors='coerce')
        if col_values.notna().any():
            idx = col_values.idxmax() if direction == "highest" else col_values.idxmin()
            print(f"  • Best {metric}: {df.loc[idx, 'Model']} ({df.loc[idx, metric]})")

    print("\n📊 METRICS TABLE:")
    display_cols = [
        'Model', 'Test Accuracy', 'Test F1-Macro', 'F1 Adequate', 'F1 Warning', 'F1 Severe',
        'F1 Critical', 'Total Time (s)', 'Device'
    ]
    display_cols = [col for col in display_cols if col in df.columns]
    print(tabulate(df[display_cols], headers='keys', tablefmt='grid', showindex=False))

def generate_report(files: Optional[List[Path]] = None,
                    results_dir: Optional[Path] = None,
                    output_plot: Optional[Path] = None,
                    export_csv: Optional[Path] = None):
    """Load results, generate summary table and plot comparison."""
    if results_dir:
        result_files = find_result_files(results_dir)
        if not result_files:
            print(f"❌ No results found in: {results_dir}")
            return
    elif files:
        result_files = files
    else:
        print("❌ Must provide --results-dir or --files.")
        return

    results = [load_results(f) for f in result_files if f.exists()]
    if not results:
        print("❌ No valid results loaded.")
        return

    df = create_comparison_table(results)
    df['Device'] = df['Device'].replace('CUDA', 'GPU')
    print_summary(df)
    plot_metrics_comparison(df, output_plot)

    if export_csv:
        df.to_csv(export_csv, index=False)
        print(f"✓ Exported comparison table to: {export_csv}")

def main():
    """Command-line entry point for result comparison."""
    parser = argparse.ArgumentParser(
        description="Compare multiple AIMS training result files.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--results-dir", type=Path, help="Directory to search for result JSON files.")
    group.add_argument("--files", type=Path, nargs='+', help="Specific result JSON files to compare.")
    parser.add_argument("--output-plot", type=Path, help="Optional path to save the comparison plot.")
    parser.add_argument("--export-csv", type=Path, help="Optional path to save the metrics table as CSV.")
    args = parser.parse_args()

    generate_report(
        files=args.files,
        results_dir=args.results_dir,
        output_plot=args.output_plot,
        export_csv=args.export_csv,
    )

if __name__ == "__main__":
    main()